from harness import *
async def t(h):
    print('world', await h.j("({veh:S.VEHICLES.length, peds:S.PEDS.length, boxes:S.World.boxes.length, trees:S.World.treeCount, props:S.World.props.length, slots:S.World.parkSlots.length, hotel1:!!S.World.poi.hotel1, hotel2:!!S.World.poi.hotel2})"))
    await h.pg.click('#btnPlay'); await h.sim(0.2)
    print('after play', await h.j("({state:S.Game.state, mission:!!S.Missions.active, px:S.Player.x, pz:S.Player.z})"))
    p0 = await h.j("[S.Player.x, S.Player.z]")
    await h.sim(2, {'moveY': 1})
    print('walk 2s', p0, '->', await h.j("[S.Player.x.toFixed(2), S.Player.z.toFixed(2), S.Player.state]"))
    await h.sim(1.5, {'moveX': 1, 'sprint': True}); print('sprint right', await h.j("[S.Player.x.toFixed(2), S.Player.z.toFixed(2)]"))
    await h.sim(0.05, {'jumpPressed': True}); await h.sim(0.15); print('jump y', await h.j("S.Player.y.toFixed(2)"))
    await h.sim(1)
    await h.sim(0.6, {'attackPressed': True})
    info = await h.j("""(()=>{ const v = S.VEHICLES.find(v=>v.parked && !v.driver); const lx=Math.cos(v.h), lz=-Math.sin(v.h); S.Player.place(v.x+lx*2, v.z+lz*2, 0); return {type:v.type, h:v.h}; })()""")
    print('teleported to car', info)
    await h.sim(0.1, {'enterPressed': True})
    print('in car', await h.j("S.Player.car ? S.Player.car.type : null"))
    await h.sim(3, {'accel': 1})
    print('drive 3s', await h.j("({speed:S.Player.car.speed.toFixed(1), health:S.Player.car.health.toFixed(0)})"))
    await h.sim(1, {'accel': 1, 'steer': -1})
    print('steer 1s', await h.j("({h:S.Player.car.h.toFixed(2), speed:S.Player.car.speed.toFixed(1)})"))
    await h.sim(3, {'accel': -1}); print('brake+reverse 3s', await h.j("({vF:S.Player.car.vF.toFixed(1)})"))
    await h.sim(0.5)
    await h.sim(0.1, {'enterPressed': True}); await h.sim(0.3)
    print('exited', await h.j("({car:!!S.Player.car, state:S.Player.state})"))
    print('NaN entities', await h.j("S.VEHICLES.filter(v=>!Number.isFinite(v.x+v.z+v.h+v.vx+v.vz+v.y)).length + S.PEDS.filter(p=>!Number.isFinite(p.x+p.z+p.y)).length"))
go(t)
